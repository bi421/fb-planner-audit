"""Audit logic and plan generation for fb-planner-audit."""
from __future__ import annotations

import json
import logging
from datetime import datetime, timezone
from typing import Any, Dict

from core.db import get_user, save_audit

try:
    from core.precheck import scan_text
except Exception:  # pragma: no cover
    scan_text = None

logger = logging.getLogger(__name__)


class RiskLevel:
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


def check_text_risk(text: str) -> Dict[str, Any]:
    """Return risk analysis for the supplied text."""
    if not text:
        return {
            "risk_level": RiskLevel.LOW,
            "score": 0,
            "risky_words": [],
            "suggestions": [],
        }

    if scan_text is None:
        lower = text.lower()
        found = [w for w in ["cheap", "guaranteed returns", "free money", "discount"] if w in lower]
        score = min(len(found) * 25, 100)
        level = RiskLevel.HIGH if score >= 70 else RiskLevel.MEDIUM if score >= 30 else RiskLevel.LOW
        suggestions = [f"Replace '{w}' with neutral language." for w in found]
        return {
            "risk_level": level,
            "score": score,
            "risky_words": found,
            "suggestions": suggestions,
        }

    result = scan_text(text)
    if not isinstance(result, dict):
        result = {}
    risk_score = int(result.get("risk_score", 0) or 0)
    status = result.get("status")

    level = RiskLevel.HIGH if risk_score > 70 or status == "warn" else RiskLevel.LOW
    risky_words = ["; ".join([str(r) for r in result.get("reasons", [])])] if result.get("reasons") else []
    suggestions = [
        "⚠️ Эрсдэлтэй үг/амлалт агуулж байна. Илүү төвийг сахисан, баталгаагүй хэллэг ашиглаарай."
    ] if risk_score > 70 else []

    return {
        "risk_level": level,
        "score": min(max(risk_score, 0), 100),
        "risky_words": risky_words,
        "suggestions": suggestions,
    }


def generate_plan(page_id: str) -> str:
    """Return a simple markdown marketing plan for the page."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    plan = f"""# Marketing Plan — {page_id}

**Generated:** {now}
**Horizon:** 30 days

## Week 1 — Foundation
- Review previous audit findings.
- Update profile bio and cover with current offer.
- Publish 3 posts introducing core products.

## Week 2 — Amplification
- Run a small boosted post focused on top-performing post.
- Add 5 new creatives to the content bank.

## Week 3 — Engagement
- Respond to every comment within 4 hours.
- Launch a simple lead magnet tied to your audience pain point.

## Week 4 — Review
- Re-run audit and compare risk score.
- Adjust budget toward winning ad set.
- Schedule next 30-day cycle.

---
*Auto-generated by fb-planner-audit*
"""
    return plan


def run_audit(url: str = "") -> Dict[str, Any]:
    """Placeholder audit returning a fixed result."""
    issues: list[Dict[str, str]] = []
    try:
        import requests as req

        resp = req.get(url, timeout=10) if url else None
        _ = resp.text if resp and resp.ok else ""
        issues = [
            {
                "type": "info",
                "message": "Audit placeholder — integrate real checker.",
            }
        ]
    except Exception as exc:
        logger.debug("Audit fetch failed: %s", exc)
        issues = [{"type": "warn", "message": "Could not fetch URL for audit."}]
    return {
        "risk_score": 0,
        "issues": issues,
        "checked_at": datetime.now(timezone.utc).isoformat(),
        "horizon_days": 30,
    }


def perform_user_audit(psid: str, url: str = "") -> Dict[str, Any]:
    """Run audit, persist result, return dict ready for messaging."""
    user = get_user(psid)
    if not user:
        return {"error": "user_not_found"}
    result = run_audit(url)
    save_audit(
        user_id=psid,
        url=url,
        risk_score=result["risk_score"],
        issues_json=json.dumps(result["issues"]),
    )
    return result


def audit_creative(text: str, image_path: str | None = None) -> Dict[str, Any]:
    """Produce a heuristic creative audit; never claim guaranteed Meta approval."""
    import re

    source = text or ""
    findings = []
    fixed = source
    scan = scan_text(source) if scan_text else {"risk_score": 0, "found_words": [], "reasons": []}
    for item in scan.get("found_words", []):
        findings.append({
            "rule": "risky_claim",
            "severity": item.get("severity", "medium"),
            "matched_text": item.get("word", ""),
            "suggestion": item.get("suggestion", "Use specific, substantiated wording."),
            "policy_link": item.get("policy_link", "https://transparency.meta.com/policies/ad-standards/"),
        })
        term = str(item.get("word", ""))
        suggestion = str(item.get("suggestion", ""))
        if term and suggestion:
            fixed = re.sub(re.escape(term), suggestion, fixed, flags=re.IGNORECASE)

    if len(source) > 2200:
        findings.append({"rule": "text_length", "severity": "medium", "matched_text": str(len(source)),
                         "suggestion": "Shorten the copy and put the main offer first."})
    letters = [ch for ch in source if ch.isalpha()]
    if len(letters) >= 12 and sum(ch.isupper() for ch in letters) / len(letters) > 0.35:
        findings.append({"rule": "excessive_caps", "severity": "medium", "suggestion": "Use sentence case and reserve capitals for short headings."})
    emoji_count = len(re.findall(r"[\U0001F300-\U0001FAFF\U00002600-\U000027BF]", source))
    if emoji_count >= 8 or (len(source) > 0 and emoji_count / max(1, len(source)) > 0.12):
        findings.append({"rule": "emoji_spam", "severity": "medium", "suggestion": "Reduce emojis and keep the call to action readable."})
    if re.search(r"before\s+and\s+after|өмнө\s+ба\s+дараа", source, re.IGNORECASE):
        findings.append({"rule": "before_after_claim", "severity": "high",
                         "suggestion": "Avoid before/after framing, especially for personal attributes or health/weight outcomes.",
                         "policy_link": "https://transparency.meta.com/policies/ad-standards/"})

    ocr = {"available": False, "text": "", "dense_text_warning": False, "note": "OCR not run"}
    if image_path:
        try:
            from PIL import Image
            import pytesseract
            with Image.open(image_path) as image:
                image_text = pytesseract.image_to_string(image)
                ocr = {
                    "available": True,
                    "text": image_text[:5000],
                    "dense_text_warning": len(image_text.strip()) > 500,
                    "note": "Text density is a review heuristic; Meta's former fixed 20% text rule is not treated as a current ban.",
                }
                if ocr["dense_text_warning"]:
                    findings.append({"rule": "image_text_density", "severity": "medium",
                                     "suggestion": "Review whether the image is overly text-heavy; keep key text concise."})
        except (ImportError, OSError, RuntimeError) as exc:
            ocr = {"available": False, "text": "", "dense_text_warning": False,
                   "note": f"OCR unavailable: {type(exc).__name__}"}

    high = sum(1 for x in findings if x.get("severity") == "high")
    medium = sum(1 for x in findings if x.get("severity") != "high")
    score = max(0, min(100, int(scan.get("risk_score", 0)) + high * 18 + medium * 8))
    risk_level = "DANGER" if score >= 60 or high >= 2 else "WARNING" if score >= 20 or findings else "SAFE"
    return {
        "score": score,
        "risk_level": risk_level,
        "failed_rules": findings,
        "fixed_version_of_copy": fixed,
        "ocr": ocr,
        "disclaimer": "Heuristic pre-check only. It cannot guarantee Meta approval or prevent account restrictions.",
    }
