-- Supabase SQL Editor: run once before deploying the Postgres-backed application.
create table if not exists public.users (
  psid text primary key,
  tier text not null default 'free' check (tier in ('free','starter','agency')),
  quota_used integer not null default 0 check (quota_used >= 0),
  quota_limit integer not null default 5 check (quota_limit >= 0),
  expires_at timestamptz,
  page_id text,
  page_name text,
  page_token text,
  last_audit_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.scans (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(psid) on delete cascade,
  input_text text not null,
  risky_words_found jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  user_id text not null references public.users(psid) on delete cascade,
  invoice_id text unique not null,
  amount integer not null check (amount > 0),
  plan text not null check (plan in ('starter','agency')),
  status text not null default 'pending' check (status in ('pending','paid','failed','expired')),
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

create index if not exists scans_user_created_idx on public.scans(user_id, created_at desc);
create index if not exists invoices_user_created_idx on public.invoices(user_id, created_at desc);
create index if not exists invoices_pending_idx on public.invoices(status) where status = 'pending';

alter table public.users enable row level security;
alter table public.scans enable row level security;
alter table public.invoices enable row level security;

